/**
 * Гарантированная уборка Chrome после проверки.
 *
 * Зачем отдельный модуль. Chrome поднимают два места: браузерная диагностика и Lighthouse.
 * В обоих стояло `try { await chrome.kill(); } catch {}`, и пустой обработчик прятал
 * настоящую проблему: замерено на боевом сервере, что через десять минут после окончания
 * прогона четыре процесса Chrome продолжали жить, суммарно на сто двадцать мегабайт.
 * Родителем был наш же процесс Node.
 *
 * На машине с четырьмя гигабайтами памяти, где рядом работают другие службы, каждая такая
 * утечка приближает отказ. И отказ выглядит не как «кончилась память», а как таймаут
 * проверки: nginx рубит запрос, человек видит «сервис недоступен», и по этому сообщению
 * причину не найти.
 *
 * Поэтому здесь: убиваем, ПРОВЕРЯЕМ, что убился, при необходимости добиваем, и в любом
 * случае пишем в журнал. Молчать об этом нельзя.
 */

import { readFileSync } from 'node:fs';
import { freemem } from 'node:os';

/** Сколько ждать добровольного завершения, прежде чем добивать. */
const GRACE_MS = 3000;

/**
 * Закрывает Chrome и убеждается, что процесса больше нет.
 * @param {{pid?: number, kill?: () => Promise<void>}} chrome то, что вернул chrome-launcher
 */
export async function killChrome(chrome) {
  if (!chrome) return;
  const pid = chrome.pid;

  try {
    await chrome.kill();
  } catch (error) {
    console.warn(`Chrome не закрылся штатно (pid ${pid ?? '?'}): ${error?.message ?? error}`);
  }

  if (!pid) return;

  // Дочерние процессы Chrome умирают вместе с главным, поэтому проверяем и добиваем
  // только его. Отдельно ходить по дереву не нужно.
  if (!alive(pid)) return;

  await new Promise((resolve) => setTimeout(resolve, GRACE_MS));
  if (!alive(pid)) return;

  try {
    process.kill(pid, 'SIGKILL');
    console.warn(`Chrome не отвечал на закрытие, добит принудительно (pid ${pid}).`);
  } catch (error) {
    // Единственный случай, когда это нормально: процесс успел закончиться сам между
    // проверкой и убийством.
    if (error?.code !== 'ESRCH') {
      console.warn(`Chrome остался жить (pid ${pid}): ${error?.message ?? error}`);
    }
  }
}

/** Существует ли ещё процесс. Сигнал 0 ничего не делает, только проверяет. */
function alive(pid) {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

/**
 * Флаги запуска Chrome, общие для диагностики и Lighthouse.
 *
 * Раньше списки в двух местах разошлись: в одном стоял --disable-dev-shm-usage, в другом
 * нет, и на машине с маленьким /dev/shm поведение отличалось между двумя частями одной
 * проверки. Отключённое здесь нужно ровно затем, чтобы Chrome занимал меньше памяти: на
 * этой машине её мало, и каждый лишний десяток мегабайт приближает отказ.
 */
export const CHROME_FLAGS = [
  '--headless=new',
  '--no-sandbox',
  '--disable-gpu',
  // Иначе Chrome пишет в /dev/shm, который в контейнерах и на VPS бывает крошечным.
  '--disable-dev-shm-usage',
  // Ничего из этого для чтения одной страницы не нужно, а память занимает.
  '--disable-extensions',
  '--disable-background-networking',
  '--disable-sync',
  '--disable-default-apps',
  '--no-first-run',
  '--no-default-browser-check',
  '--mute-audio'
];

/**
 * Хватит ли памяти, чтобы поднять Chrome.
 *
 * Зачем проверять заранее. Chrome на одну страницу занимает от полутора сотен мегабайт.
 * Если свободной памяти меньше, он либо не запустится, либо запустится и будет ползать:
 * запрос упирается в таймаут nginx, и человек видит «сервис недоступен». По такому
 * сообщению причину не найти, а причина простая и её можно назвать вслух.
 *
 * Замерено на боевом сервере: при 107 МБ доступной памяти и средней загрузке 6.35 две
 * глубокие проверки подряд закончились ответом 504 от nginx. Причём проверка страниц
 * успела отработать полностью, то есть терялась только браузерная часть, а человек
 * получал общий отказ вместо результата.
 *
 * Порог с запасом: Chrome разворачивается не сразу и в процессе занимает больше, чем
 * в покое.
 */
const MIN_AVAILABLE_MB = 350;

export function chromeMemoryCheck() {
  const availableMb = availableMemoryMb();
  if (availableMb === null || availableMb >= MIN_AVAILABLE_MB) {
    return { ok: true, availableMb };
  }
  return {
    ok: false,
    availableMb,
    reason: `На сервере сейчас мало свободной памяти (${availableMb} МБ), поэтому браузерную часть проверки мы пропустили: она подняла бы Chrome и почти наверняка не успела бы. Проверка самих страниц при этом полная. Попробуйте запустить браузерную часть через несколько минут.`
  };
}

/**
 * Сколько памяти реально можно занять, в мегабайтах.
 *
 * os.freemem() на Linux отдаёт MemFree, а он не учитывает кеш, который система отдаст по
 * первому требованию. На машине с занятым кешем это число сильно ниже правды, и проверка
 * отказывала бы там, где памяти достаточно. Поэтому сначала читаем MemAvailable из
 * /proc/meminfo, а os.freemem() оставляем для систем без procfs.
 */
function availableMemoryMb() {
  try {
    const info = readFileSync('/proc/meminfo', 'utf8');
    const match = info.match(/^MemAvailable:\s+(\d+)\s+kB$/m);
    if (match) return Math.round(Number(match[1]) / 1024);
  } catch {
    // Не Linux или нет доступа к procfs: спрашиваем у Node.
  }
  try {
    return Math.round(freemem() / 1048576);
  } catch {
    // Не смогли узнать вообще: тогда не мешаем работать.
    return null;
  }
}
