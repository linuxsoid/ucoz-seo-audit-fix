/**
 * Человеческое описание проблемы по её коду.
 *
 * Коды Lighthouse сюда не попадают: их формулировки приходят от самого Lighthouse и уже
 * записаны в проверку. Для незнакомого кода возвращаем null, и тогда отчёт печатает
 * исходное сообщение движка. Так новая проверка не ломает отчёт, а просто выглядит суше,
 * пока для неё не написали человеческий текст.
 */
export function humanize(code) {
  const entry = L[String(code)];
  if (!entry) return null;
  return { ...entry, effortLabel: EFFORT[entry.effort] ?? '' };
}

/** Сколько кодов уже переведено. Нужно тесту, чтобы новая проверка не осталась без текста. */
export function humanizedCodes() {
  return Object.keys(L);
}
